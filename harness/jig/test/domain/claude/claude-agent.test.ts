import { describe, expect, test } from "bun:test";
import { modelChoiceFor, parseAgentDefinition } from "../../../src/domain/claude/agent-definition";
import { isClaudeModelName, renderClaudeAgent } from "../../../src/domain/claude/claude-agent";

const SOURCE = [
  "---",
  "name: architect",
  "description: Plans.",
  "tools: [Read, Grep]",
  "model: complex",
  "effort: xhigh",
  "---",
  "",
  "You design.",
  "",
].join("\n");

describe("renderClaudeAgent", () => {
  const definition = parseAgentDefinition(SOURCE, "architect");

  test("the tier becomes the Claude alias, a provenance comment is added, the rest is verbatim", () => {
    const text = renderClaudeAgent({
      text: SOURCE,
      model: modelChoiceFor(definition.model, { complex: { model: "opus" } }),
      sourcePath: "/repo/agents/architect.md",
    });
    expect(text).toBe(
      [
        "---",
        "# generated by jig apply --target claude from /repo/agents/architect.md — edit the source, not this file",
        "name: architect",
        "description: Plans.",
        "tools: [Read, Grep]",
        "model: opus",
        "effort: xhigh",
        "---",
        "",
        "You design.",
        "",
      ].join("\n"),
    );
  });

  test("an inherited or unmapped model drops the model line, so Claude Code uses the parent's", () => {
    for (const model of [modelChoiceFor(undefined, {}), modelChoiceFor("complex", {})]) {
      const text = renderClaudeAgent({ text: SOURCE, model, sourcePath: "/repo/agents/a.md" });
      expect(text).not.toContain("\nmodel:");
      expect(text).toContain("\neffort: xhigh\n");
    }
  });

  test("a source without frontmatter is returned with a provenance block only", () => {
    const text = renderClaudeAgent({
      text: "just a prompt\n",
      model: modelChoiceFor(undefined, {}),
      sourcePath: "/repo/agents/p.md",
    });
    expect(
      text.startsWith("---\n# generated by jig apply --target claude from /repo/agents/p.md"),
    ).toBe(true);
    expect(text.endsWith("---\njust a prompt\n")).toBe(true);
  });
});

describe("renderClaudeAgent: an override with no model line", () => {
  test("a mapped choice adds the model line the source does not have", () => {
    const text = renderClaudeAgent({
      text: "---\nname: a\nmodels: { claude: { model: haiku } }\n---\nx\n",
      model: { kind: "mapped", model: "haiku", override: true },
      sourcePath: "/repo/agents/a.md",
    });
    expect(text).toContain("\nmodel: haiku\n---\n");
  });

  test("isClaudeModelName knows the aliases and claude-* ids, not house tiers", () => {
    expect(isClaudeModelName("sonnet")).toBe(true);
    expect(isClaudeModelName("claude-opus-5-5")).toBe(true);
    expect(isClaudeModelName("main")).toBe(false);
    expect(isClaudeModelName("gpt-6-sol")).toBe(false);
  });
});
