/**
 * `~/.claude/agents/<name>.md`, generated from the house or pack source. The
 * source is already a Claude Code subagent, so the text is copied as written
 * with one change: `model:` holds a house tier (`main`, `complex`,
 * `executor`), which Claude Code does not know, and is replaced by the alias
 * the `claude` table of `agents/models.json` maps it to — or dropped when the
 * agent inherits or the table has no entry, so Claude Code uses the parent's
 * model (rules/decisions/2026-10-19-model-assignment.md). `effort:` uses
 * Claude Code's own levels and passes through.
 *
 * Pure: the source text in, the file's text out.
 */

import type { ModelChoice } from "./agent-definition";

const FRONTMATTER_RE = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/;

export interface ClaudeAgentInput {
  /** The source file's text, as read. */
  readonly text: string;
  readonly model: ModelChoice;
  /** Absolute path of the source, for the provenance comment. */
  readonly sourcePath: string;
}

export function renderClaudeAgent(input: ClaudeAgentInput): string {
  const provenance = `# generated by jig apply --target claude from ${input.sourcePath} — edit the source, not this file`;
  const match = FRONTMATTER_RE.exec(input.text);
  if (match === null) return `---\n${provenance}\n---\n${input.text}`;
  const mapped = input.model.kind === "mapped" ? `model: ${input.model.model}` : undefined;
  const source = (match[1] ?? "").split(/\r?\n/);
  const lines = source.flatMap((line) => {
    if (!line.startsWith("model:")) return [line];
    return mapped === undefined ? [] : [mapped];
  });
  // A `models.claude` override maps an agent that writes no `model:` line.
  if (mapped !== undefined && !source.some((line) => line.startsWith("model:"))) {
    lines.push(mapped);
  }
  const rest = input.text.slice(match[0].length);
  return `---\n${provenance}\n${lines.join("\n")}\n---\n${rest}`;
}

/** A model name Claude Code itself understands: an alias or a full `claude-*` id. */
export function isClaudeModelName(model: string): boolean {
  return /^(opus|sonnet|haiku|fable)$/.test(model) || model.startsWith("claude-");
}
