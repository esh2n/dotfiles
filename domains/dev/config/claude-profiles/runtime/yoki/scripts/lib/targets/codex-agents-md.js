'use strict';

/**
 * `~/.codex/AGENTS.md` managed block: `core/CLAUDE.layer.md` +
 * `personal/CLAUDE.personal.md` + every rule file with no `paths:`
 * frontmatter (conditional rules only apply when a matching file type is
 * present in the project — see core/rules/README.md — so only the
 * always-on ones belong in the harness-level instructions), run through a
 * Claude → Codex vocabulary substitution.
 */

const { extractBlock, wrapBlock } = require('./managed-block');

const BLOCK_START = '<!-- yoki:begin -->';
const BLOCK_END = '<!-- yoki:end -->';

/** A rule file has `paths:` frontmatter when its frontmatter block (the
 * text between the first two `---` lines) contains a `paths:` key —
 * common/git-workflow.md is the one rule file that deliberately omits it
 * (core/rules/README.md: "stays always-on"). */
function hasPathsFrontmatter(markdown) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---/.exec(String(markdown || ''));
  if (!m) return false;
  return /^paths:/m.test(m[1]);
}

/** Substitutes every vocab entry, longest key first so e.g. `~/.claude/`
 * is applied before a shorter `~/.claude` entry would double-substitute
 * the trailing slash. Plain string replace (not regex) — vocab entries are
 * literal text, not patterns. */
function substituteVocab(text, vocab) {
  const keys = Object.keys(vocab).filter(k => k !== '_comment').sort((a, b) => b.length - a.length);
  return keys.reduce((acc, key) => acc.split(key).join(vocab[key]), String(text || ''));
}

/**
 * @param {{claudeLayerMd?: string, claudePersonalMd?: string,
 *   noPathsRules: Array<{path: string, content: string}>, vocab: Record<string,string>}} opts
 * @returns {string} the block content, without the `<!-- yoki:begin -->`/`<!-- yoki:end -->` markers
 */
function buildAgentsMdBlockContent(opts) {
  const { claudeLayerMd, claudePersonalMd, noPathsRules, vocab } = opts;
  const sections = [
    '<!-- GENERATED by yoki lib/targets/gen.js --target codex. Edit the claude-profiles layers instead. -->',
  ];

  if (claudeLayerMd) sections.push(substituteVocab(claudeLayerMd, vocab).trim());
  if (claudePersonalMd) sections.push(substituteVocab(claudePersonalMd, vocab).trim());

  for (const rule of noPathsRules) {
    sections.push(substituteVocab(rule.content, vocab).trim());
  }

  return sections.join('\n\n');
}

/**
 * @param {string} existingText current `~/.codex/AGENTS.md` content (empty string if absent)
 * @param {string} blockContent from buildAgentsMdBlockContent
 * @returns {string} the full file content, block at the top, rest preserved
 */
function applyAgentsMdBlock(existingText, blockContent) {
  const { after } = extractBlock(existingText || '', BLOCK_START, BLOCK_END);
  return wrapBlock(BLOCK_START, BLOCK_END, blockContent, after);
}

module.exports = {
  BLOCK_START,
  BLOCK_END,
  hasPathsFrontmatter,
  substituteVocab,
  buildAgentsMdBlockContent,
  applyAgentsMdBlock,
};
