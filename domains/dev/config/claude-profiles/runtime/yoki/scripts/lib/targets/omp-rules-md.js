'use strict';

/**
 * `~/.omp/agent/RULES.md` managed block — every rule file with no `paths:`
 * frontmatter (conditional rules only apply when a matching file type is
 * present in a project — core/rules/README.md — so only the always-on ones
 * belong in omp's always-loaded RULES.md), plus a pointer line for the
 * conditional ones. Unlike Codex's AGENTS.md (codex-agents-md.js), no
 * CLAUDE.md content and no vocabulary substitution belong here: omp's own
 * `claude` discovery provider already reads `~/.claude/CLAUDE.md` and
 * `.claude/CLAUDE.md` directly (spike S4-S5 (a)), so RULES.md only needs to
 * cover the one thing omp does NOT read on its own — `~/.claude/rules/`.
 */

const { extractBlock, wrapBlock } = require('./managed-block');
const { hasPathsFrontmatter } = require('./codex-agents-md');

const BLOCK_START = '<!-- yoki:begin -->';
const BLOCK_END = '<!-- yoki:end -->';

const POINTER_LINE = 'Conditional rules (scoped by `paths:` frontmatter to specific file types) are injected by the yoki pre-rules-context hook, not listed here.';

/**
 * @param {Array<{relPath: string, absPath: string}>} ruleFiles every layer's
 *   `rules/**\/*.md`, already read via readTextIfExists by the caller
 * @param {(absPath: string) => string|null} readText
 * @returns {string} the block content, without the begin/end markers
 */
function buildRulesMdBlockContent(ruleFiles, readText) {
  const sections = [
    '<!-- GENERATED by yoki lib/targets/gen.js --target omp. Edit the claude-profiles rules layers instead. -->',
    POINTER_LINE,
  ];

  for (const f of ruleFiles) {
    const text = readText(f.absPath);
    if (text && !hasPathsFrontmatter(text)) sections.push(text.trim());
  }

  return sections.join('\n\n');
}

/**
 * @param {string} existingText current `~/.omp/agent/RULES.md` content
 *   (empty string if absent)
 * @param {string} blockContent from buildRulesMdBlockContent
 */
function applyRulesMdBlock(existingText, blockContent) {
  const { after } = extractBlock(existingText || '', BLOCK_START, BLOCK_END);
  return wrapBlock(BLOCK_START, BLOCK_END, blockContent, after);
}

module.exports = { BLOCK_START, BLOCK_END, POINTER_LINE, buildRulesMdBlockContent, applyRulesMdBlock };
