'use strict';

/**
 * `~/.codex/config.toml` managed block: a `# yoki:begin` / `# yoki:end`
 * section placed at the TOP of the file, because Codex requires top-level
 * keys (`default_permissions`, `notify`) to precede any `[table]` header
 * (spike S3 §1, run 4: a misplaced `default_permissions` silently became
 * `features.default_permissions` and failed config load).
 *
 * Everything outside the block is preserved byte-for-byte. If the file
 * already declares a top-level `default_permissions` or `sandbox_mode`
 * outside the block, ours is not emitted (S3 §1: "Don't combine with
 * `sandbox_mode`") and the caller gets a warning to surface via `doctor`.
 */

const { extractBlock, wrapBlock } = require('./managed-block');

const BLOCK_START = '# yoki:begin';
const BLOCK_END = '# yoki:end';
const CONFLICT_KEYS_RE = /^\s*(default_permissions|sandbox_mode)\s*=/;
const TABLE_HEADER_RE = /^\s*\[/;

function toTomlString(value) {
  return JSON.stringify(String(value));
}

/**
 * @param {{permissionsToml: string, yokiRoot: string, pluginRoot: string,
 *   hookProfile: string, hookStateEntries: Array<{key: string, trustedHash: string}>,
 *   mcpServersToml?: string}} opts `mcpServersToml` (task T13, from
 *   `lib/mcp-inventory/writers/codex.js` buildMcpServersToml) is the
 *   pre-rendered `[mcp_servers.<name>]` TOML tables, appended verbatim after
 *   the hook-state entries; omitted/empty when there is nothing to emit.
 * @returns {string} the block content, without the `# yoki:begin`/`# yoki:end` markers
 */
function buildManagedBlockContent(opts) {
  const { permissionsToml, yokiRoot, pluginRoot, hookProfile, hookStateEntries, mcpServersToml } = opts;

  // permissionsToml (lib/permissions/to-codex.js toPermissionsToml) already
  // contains `default_permissions = "yoki"` plus the [permissions.yoki*]
  // tables — strip its leading comment and default_permissions line since
  // this block composes its own top-level keys first, in the required order.
  const permissionsLines = permissionsToml
    .split('\n')
    .filter(line => !line.startsWith('#') && line.trim() !== 'default_permissions = "yoki"');
  while (permissionsLines.length && permissionsLines[0] === '') permissionsLines.shift();

  const lines = [
    '# GENERATED by yoki lib/targets/gen.js --target codex. Do not edit inside this block —',
    '# your changes will be discarded on the next apply. Edit the claude-profiles layers instead.',
    'default_permissions = "yoki"',
    `notify = ["node", ${toTomlString(`${yokiRoot}/scripts/hooks/codex-notify.js`)}]`,
    '',
    ...permissionsLines,
    '[features]',
    'hooks = true',
    'multi_agent = true',
    '',
    '[agents]',
    'enabled = true',
    'max_concurrent_threads_per_session = 4',
    '',
    '[shell_environment_policy.set]',
    `YOKI_ROOT = ${toTomlString(yokiRoot)}`,
    `CLAUDE_PLUGIN_ROOT = ${toTomlString(pluginRoot)}`,
    `YOKI_HOOK_PROFILE = ${toTomlString(hookProfile)}`,
    'YOKI_HARNESS = "codex"',
    '',
  ];

  for (const entry of hookStateEntries) {
    lines.push(`[hooks.state.${toTomlString(entry.key)}]`);
    lines.push(`trusted_hash = ${toTomlString(entry.trustedHash)}`);
    lines.push('enabled = true');
    lines.push('');
  }

  if (mcpServersToml) {
    lines.push(mcpServersToml);
    lines.push('');
  }

  // Trim a single trailing blank line; the caller adds exactly one.
  while (lines.length && lines[lines.length - 1] === '') lines.pop();

  return lines.join('\n');
}

/** True when `rest` (the file content with our own block already removed)
 * declares a conflicting top-level key before its first `[table]` header. */
function hasConflictingTopLevelKey(rest) {
  for (const line of rest.split('\n')) {
    if (TABLE_HEADER_RE.test(line)) return false;
    if (CONFLICT_KEYS_RE.test(line)) return true;
  }
  return false;
}

/** Strips `[hooks.state."<key>"]` sections from `rest` whose key is one of
 * `keysToRemove` — cleanup for older installs that wrote trust entries
 * outside the managed block (spec: "remove them"). */
function removeHookStateSections(rest, keysToRemove) {
  if (!keysToRemove || keysToRemove.size === 0) return rest;

  const lines = rest.split('\n');
  const kept = [];
  let skipping = false;

  for (const line of lines) {
    const header = /^\[hooks\.state\.(.+)\]\s*$/.exec(line.trim());
    if (header) {
      let key;
      try {
        key = JSON.parse(header[1]);
      } catch {
        key = header[1];
      }
      skipping = keysToRemove.has(key);
      if (skipping) continue;
    } else if (skipping && TABLE_HEADER_RE.test(line)) {
      skipping = false;
    }
    if (!skipping) kept.push(line);
  }

  return kept.join('\n');
}

/**
 * @param {string} existingText current `~/.codex/config.toml` content (empty string if absent)
 * @param {string} blockContent from buildManagedBlockContent
 * @param {Set<string>} ownedHookStateKeys keys this apply is about to (re-)emit
 * @returns {{content: string, warnings: string[]}}
 */
function applyManagedBlock(existingText, blockContent, ownedHookStateKeys) {
  const { after } = extractBlock(existingText || '', BLOCK_START, BLOCK_END);
  const warnings = [];

  if (hasConflictingTopLevelKey(after)) {
    warnings.push(
      'codex: config.toml already declares a top-level default_permissions/sandbox_mode outside the managed block — ' +
      'the yoki permissions block was NOT written (S3: do not combine default_permissions with sandbox_mode). Remove the ' +
      'conflicting key by hand, then re-run.'
    );
    return { content: existingText || '', warnings };
  }

  const cleanedAfter = removeHookStateSections(after, ownedHookStateKeys);
  const content = wrapBlock(BLOCK_START, BLOCK_END, blockContent, cleanedAfter);
  return { content, warnings };
}

module.exports = {
  BLOCK_START,
  BLOCK_END,
  buildManagedBlockContent,
  hasConflictingTopLevelKey,
  removeHookStateSections,
  applyManagedBlock,
};
